"""
Check equal material increments and reject length generated by rigid-profile roll.
"""

import math

import pytest

from cable_bundler.routing.geometry import Vector3, difference, dot, magnitude
from devtools.ribbon_analysis.isometric_fold import CylindricalFold
from devtools.ribbon_analysis.material_lengths import measure_lengths
from experiments.experiment_ribbon_cap_transition.endpoint_first import EndpointCase
from experiments.experiment_ribbon_normal_route.compatibility import planar_controls
from experiments.experiment_ribbon_normal_route.solver import solve


class CompensatingPaths:
    """
    Author equal total lengths with opposing, invalid local material stretches.
    """

    @staticmethod
    def lane(u: float, offset_mm: float) -> tuple[Vector3, Vector3]:
        """
        Return monotone lines whose parameter speeds disagree locally.
        """
        scale = 0.02 * offset_mm
        point = Vector3(u + scale * math.sin(2 * math.pi * u), offset_mm, 0)
        velocity = Vector3(1 + 2 * math.pi * scale * math.cos(2 * math.pi * u), 0, 0)
        return point, velocity


def test_equal_totals_do_not_hide_local_stretch() -> None:
    """
    Expose material mismatch even when all three integrated totals are equal.
    """
    measured = measure_lengths(CompensatingPaths(), 1.0, intervals=64)
    assert measured.lengths_mm == pytest.approx((1.0, 1.0, 1.0))
    assert measured.maximum_sampled_relative_speed_spread > 0.2


@pytest.mark.parametrize(
    "bank,angle",
    [
        (0.0, math.pi / 2),
        (math.pi / 4, math.pi / 2),
        (-math.pi / 4, -math.pi),
        (math.pi / 4, math.pi),
    ],
)
def test_fold_preserves_local_metric_and_all_lane_lengths(bank: float, angle: float) -> None:
    """
    Check the world-space map independently through derivatives and path integration.
    """
    fold = CylindricalFold(1.0, angle, bank, 4.8, 3.0, 3.0)
    for q in (-2.4, -1.2, 0.0, 1.2, 2.4):
        low, high = fold.bend_interval(q)
        for u in (low / 2, (low + high) / 2, (1 + high) / 2):
            point, velocity, across, acceleration = fold.surface(u, q)
            assert magnitude(velocity) == pytest.approx(fold.material_length_mm)
            assert magnitude(across) == pytest.approx(1)
            assert abs(dot(velocity, across)) < 1e-12
            assert abs(dot(acceleration, across)) < 1e-10
            before, _ = fold.lane(u - 1e-6, q)
            after, _ = fold.lane(u + 1e-6, q)
            delta = difference(after, before)
            numerical = Vector3(delta.x / 2e-6, delta.y / 2e-6, delta.z / 2e-6)
            assert magnitude(difference(numerical, velocity)) < 1e-6
            if abs(q) < 2.4:
                delta = difference(fold.lane(u, q + 1e-6)[0], fold.lane(u, q - 1e-6)[0])
                numerical = Vector3(delta.x / 2e-6, delta.y / 2e-6, delta.z / 2e-6)
                assert magnitude(difference(numerical, across)) < 1e-8
            assert all(math.isfinite(value) for value in (point.x, point.y, point.z))
    result = measure_lengths(fold, 2.4, intervals=64)
    assert result.lengths_mm == pytest.approx((fold.material_length_mm,) * 3)
    assert result.spread_mm < 1e-12
    assert result.maximum_sampled_relative_speed_spread < 1e-14


def test_diagonal_fold_has_flat_caps_and_staggered_material_entries() -> None:
    """
    Preserve straight terminal profiles while curving transverse lines in the fold.
    """
    fold = CylindricalFold(1.0, math.pi / 2, math.pi / 4, 4.8, 3.0, 3.0)
    for u in (0.0, 1.0):
        center, _, width, _ = fold.surface(u, 0)
        for q in (-2.4, 2.4):
            actual, _ = fold.lane(u, q)
            assert magnitude(difference(actual, center.translated(width, q))) < 1e-12
    assert fold.bend_interval(2.4)[0] < fold.bend_interval(0)[0] < fold.bend_interval(-2.4)[0]
    left, _ = fold.lane(0.5, 2.4)
    right, _ = fold.lane(0.5, -2.4)
    assert magnitude(difference(left, right)) < 4.8
    # The width's material arc length is4.8; its shorter chord is not compression.


def test_rigid_normal_roll_is_rejected_despite_certified_curvature() -> None:
    """
    Expose both edges growing longer than the center instead of accepting the route.
    """
    x, y, z = Vector3(1, 0, 0), Vector3(0, 1, 0), Vector3(0, 0, 1)
    case = EndpointCase("roll", Vector3(0, 0, 0), Vector3(45, 12, 8), x, x, y, z, 3)
    result = solve(case, maximum_probes=3)
    assert result.status == "length_incompatible"
    assert result.route is not None and result.certificate is not None
    assert result.certificate.status == "certified"
    measured = measure_lengths(result.route, result.route.half_width_mm, intervals=128)
    left, center, right = measured.lengths_mm
    assert left > center + 0.1 and right > center + 0.1
    assert left == pytest.approx(right)


def test_planar_constant_width_paths_remain_equal() -> None:
    """
    Keep valid bending while distinguishing exact planarity from spatial controls.
    """
    x, y, z = Vector3(1, 0, 0), Vector3(0, 1, 0), Vector3(0, 0, 1)
    case = EndpointCase("quarter", Vector3(0, 0, 0), Vector3(20, 20, 0), x, y, z, z, 3)
    result = solve(case, maximum_probes=3)
    assert result.status == "certified" and result.route is not None
    measured = measure_lengths(result.route, result.route.half_width_mm, intervals=64)
    assert measured.spread_mm == 0
    assert planar_controls((Vector3(0, 0, 0), x, y, Vector3(1, 1, 0)))
    assert not planar_controls((Vector3(0, 0, 0), x, y, z))


