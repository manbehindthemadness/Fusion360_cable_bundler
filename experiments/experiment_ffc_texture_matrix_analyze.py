"""
Measure FFC matrix viewport captures against exact sketch contact centers.

Run after converting the ignored PNG captures to 32-bit, top-down BMP using
``sips -s format bmp``. This host-only parser does not need Fusion or Pillow.
"""

from __future__ import annotations

import colorsys
import json
import math
import statistics
import struct
import sys
from pathlib import Path

REPORT_DIR = Path(__file__).resolve().parents[1] / "artifacts/verification/ffc_texture_matrix"


def _read_bmp(path: Path) -> tuple[bytes, int, int, int]:
    """
    Read an uncompressed top-down 32-bit BMP generated by macOS sips.
    """
    data = path.read_bytes()
    if data[:2] != b"BM":
        raise ValueError(f"Not a BMP: {path}")
    offset = struct.unpack_from("<I", data, 10)[0]
    width = struct.unpack_from("<i", data, 18)[0]
    signed_height = struct.unpack_from("<i", data, 22)[0]
    bits = struct.unpack_from("<H", data, 28)[0]
    if width <= 0 or signed_height >= 0 or bits != 32:
        raise ValueError(f"Expected a top-down 32-bit BMP: {path}")
    height = -signed_height
    if len(data) < offset + 4 * width * height:
        raise ValueError(f"Incomplete BMP pixel buffer: {path}")
    return data, offset, width, height


def _color_runs(
    data: bytes, offset: int, width: int, y: int, left: int, right: int
) -> list[tuple[int, int]]:
    """
    Find saturated stripe spans on one row within the expected ribbon bounds.
    """
    runs: list[tuple[int, int]] = []
    start: int | None = None
    for x in range(left, right + 2):
        colored = False
        if x <= right:
            pixel_offset = offset + 4 * (y * width + x)
            blue, green, red = data[pixel_offset : pixel_offset + 3]
            colored = (
                max(red, green, blue) > 120 and max(red, green, blue) - min(red, green, blue) > 75
            )
        if colored and start is None:
            start = x
        elif not colored and start is not None:
            if x - start >= 4:
                runs.append((start, x - 1))
            start = None
    return runs


def _measure_case(row: dict[str, object], bmp_dir: Path, image_suffix: str) -> dict[str, object]:
    """
    Compare observed stripes with the model-space trace centers and widths.
    """
    count = int(row["count"])
    pitch_mm = float(row["pitch_mm"])
    trace_width_mm = float(row["trace_width_mm"])
    extent_cm = float(row["view_extent_cm"])
    observations: dict[str, object] = {"name": row["name"], "count": count}
    for side in ("top", "bottom"):
        image_name = Path(str(row[f"{side}_image"])).name
        bmp_path = bmp_dir / Path(image_name).with_name(
            Path(image_name).stem + image_suffix + ".bmp"
        )
        data, offset, width, height = _read_bmp(bmp_path)
        pixels_per_cm = height / extent_cm
        y = round(height / 2 - (1.0 - 0.75) * pixels_per_cm)
        half_ribbon_cm = count * pitch_mm / 20.0
        margin_cm = pitch_mm / 20.0
        left = max(0, math.floor(width / 2 - (half_ribbon_cm + margin_cm) * pixels_per_cm))
        right = min(width - 1, math.ceil(width / 2 + (half_ribbon_cm + margin_cm) * pixels_per_cm))
        runs = _color_runs(data, offset, width, y, left, right)
        centers = [(start + end) / 2 for start, end in runs]
        widths = [end - start + 1 for start, end in runs]
        expected = [
            width / 2 + (index - (count - 1) / 2) * pitch_mm / 10.0 * pixels_per_cm
            for index in range(count)
        ]
        result: dict[str, object] = {
            "band_count": len(runs),
            "expected_band_count": count,
            "observed_width_px": widths,
            "expected_width_px": trace_width_mm / 10.0 * pixels_per_cm,
            "observed_centers_px": centers,
            "expected_centers_px": expected,
        }
        if runs:
            result["outer_gaps_mm"] = [
                (runs[0][0] - (width / 2 - half_ribbon_cm * pixels_per_cm)) * 10.0 / pixels_per_cm,
                ((width / 2 + half_ribbon_cm * pixels_per_cm) - runs[-1][1]) * 10.0 / pixels_per_cm,
            ]
        if len(runs) == count:
            errors = [observed - target for observed, target in zip(centers, expected)]
            result["max_center_error_mm"] = (
                max(abs(error) for error in errors) * 10.0 / pixels_per_cm
            )
            result["mean_center_error_mm"] = statistics.mean(errors) * 10.0 / pixels_per_cm
            result["mean_width_ratio"] = statistics.mean(widths) / result["expected_width_px"]
            result["outer_width_ratio"] = [
                widths[0] / result["expected_width_px"],
                widths[-1] / result["expected_width_px"],
            ]
            hue_errors: list[float] = []
            for index, center in enumerate(centers):
                x = round(center)
                pixel_offset = offset + 4 * (y * width + x)
                blue, green, red = data[pixel_offset : pixel_offset + 3]
                observed_hue = colorsys.rgb_to_hsv(red / 255, green / 255, blue / 255)[0]
                lane = index if side == "top" else count - 1 - index
                expected_hue = (lane * 0.618033988749895) % 1.0
                difference = abs(observed_hue - expected_hue)
                hue_errors.append(min(difference, 1.0 - difference))
            result["max_hue_error"] = max(hue_errors)
        observations[side] = result
    return observations


def analyze(bmp_dir: Path, image_suffix: str = "") -> dict[str, object]:
    """
    Produce a compact, machine-readable mapping audit for all solid cases.
    """
    matrix = json.loads((REPORT_DIR / "matrix.json").read_text(encoding="utf-8"))
    results = [
        _measure_case(row, bmp_dir, image_suffix)
        for row in matrix["cases"]
        if row["result"] == "solid"
    ]
    report = {"source_matrix": str(REPORT_DIR / "matrix.json"), "cases": results}
    output = REPORT_DIR / f"matrix_analysis{image_suffix}.json"
    output.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return report


if __name__ == "__main__":
    if len(sys.argv) not in (2, 3):
        raise SystemExit(
            "Usage: experiment_ffc_texture_matrix_analyze.py <bmp-directory> [image-suffix]"
        )
    summary = analyze(Path(sys.argv[1]), sys.argv[2] if len(sys.argv) == 3 else "")
    for case in summary["cases"]:
        top, bottom = case["top"], case["bottom"]
        print(
            case["name"],
            "expected",
            case["count"],
            "bands",
            top["band_count"],
            bottom["band_count"],
            "max_error_mm",
            top.get("max_center_error_mm"),
            bottom.get("max_center_error_mm"),
            "width_ratio",
            top.get("mean_width_ratio"),
            bottom.get("mean_width_ratio"),
        )
